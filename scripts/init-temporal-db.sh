#!/bin/bash
set -e

DB_NAME="${TEMPORAL_POSTGRES_DB:-temporal_db}"
VISIBILITY_DB_NAME="${DB_NAME}_visibility"
DB_USER="${TEMPORAL_POSTGRES_USER:-temporal}"
DB_PASS="${TEMPORAL_POSTGRES_PASSWORD:-temporal_local_secret}"

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE USER $DB_USER WITH PASSWORD '$DB_PASS';

    CREATE DATABASE $DB_NAME OWNER $DB_USER;
    GRANT ALL PRIVILEGES ON DATABASE $DB_NAME TO $DB_USER;

    CREATE DATABASE $VISIBILITY_DB_NAME OWNER $DB_USER;
    GRANT ALL PRIVILEGES ON DATABASE $VISIBILITY_DB_NAME TO $DB_USER;
EOSQL
